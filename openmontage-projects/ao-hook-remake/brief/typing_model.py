"""Human typing schedules for the chatbot prompts: bursty cadence, word/punctuation pauses, one corrected typo.
Writes film/src/typingSchedule.ts (picture) and artifacts/typing_keys.json (one key click per keystroke, absolute s)."""
import json, os, random
H = os.path.expanduser('~/Desktop/AgenticOffice_Video/agentic-office-launch-film-handoff-2026-10-12/film/src/typingSchedule.ts')
J = os.path.expanduser('~/Desktop/OpenMontage/projects/ao-hook-remake/artifacts/typing_keys.json')
# id, prefilled text, typed text, typo (index in typed, wrong chars), window start/end (scene-internal s), offset to absolute s
P = [('ask1', 'DACH Q4 is now 8.5. ', 'Update the board memo.', (12, 'ao'), 0.35, 2.45, 8.0),
     ('ask2', '', 'Update the deck to match.', (13, 'kc'), 17.1, 19.2, 6.6),
     ('ask3', '', 'Slide 2: €74.6m', None, 23.45, 24.75, 6.6)]
out, keys = {}, []
for pid, pre, txt, typo, a, b, off in P:
    rnd = random.Random(pid)
    ev, cur, gaps = [], '', []
    seq = []                                    # (kind, char)
    for i, ch in enumerate(txt):
        if typo and i == typo[0]:
            for w in typo[1]: seq.append(('k', w))
            seq.append(('pause', None)); seq += [('bs', None)] * len(typo[1])
        seq.append(('k', ch))
    for kind, ch in seq:                        # raw human delays (s)
        if kind == 'pause': gaps.append(rnd.uniform(0.22, 0.32)); continue
        d = rnd.uniform(0.055, 0.115)
        if kind == 'bs': d = rnd.uniform(0.06, 0.09)
        elif cur and cur[-1] == ' ': d += rnd.uniform(0.06, 0.16)            # word start hesitates
        elif cur and cur[-1] in '.,:': d += rnd.uniform(0.12, 0.2)
        if rnd.random() < 0.12: d += rnd.uniform(0.05, 0.12)                  # micro-hesitation
        gaps.append(d)
        cur = cur[:-1] if kind == 'bs' else cur + ch
    scale = (b - a) / sum(gaps)
    t, cur, gi = a, '', 0
    for kind, ch in seq:
        t += gaps[gi] * scale; gi += 1
        if kind == 'pause': continue
        cur = cur[:-1] if kind == 'bs' else cur + ch
        ev.append([round(t, 3), cur]); keys.append(round(t + off, 3))
    out[pid] = {'pre': pre, 'ev': ev}
    print(pid, f'{len(txt) / (b - a):.1f} chars/s', 'events', len(ev))
open(H, 'w').write('// generated by ao-hook-remake/brief/typing_model.py — do not edit\nexport const TYPE: Record<string, {pre: string; ev: [number, string][]}> = ' + json.dumps(out, ensure_ascii=False) + ';\n'
  "export const typedAt = (id: string, t: number) => { const s = TYPE[id]; let c = ''; for (const [at, v] of s.ev) { if (at <= t) c = v; else break; } return s.pre + c; };\n")
json.dump(sorted(keys), open(J, 'w'))
